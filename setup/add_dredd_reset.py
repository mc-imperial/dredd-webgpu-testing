#!/usr/bin/env python3
"""Add Dredd tracking-reset calls to lavapipe, generated from the current mutation.

Run after Dredd has mutated Mesa (with --allow-reset-of-tracking-counters) and
before Mesa is compiled. It:
  1. finds every `atomic_bool __dredd_already_recorded_<N>[<SIZE>]` definition in
     the mutated sources, and checks the indices run 0..K-1 with no gaps or clashes;
  2. inserts, into lvp_pipeline.c, matching extern declarations and a
     __dredd_reset_tracking() function that clears all of them;
  3. inserts a call to __dredd_reset_tracking() at the start of
     lvp_CreateGraphicsPipelines and lvp_CreateComputePipelines.

Because the list is built from the mutated files, it always matches the build
(a hand-written patch goes stale when the mutated file set changes).

Usage:
  add_dredd_reset.py <mesa source dir> [--mutated-dir src/compiler/nir]
"""
import argparse
import re
import sys
from pathlib import Path

MARKER = "/* DREDD TRACKING RESET (generated by add_dredd_reset.py) */"
DEF_RE = re.compile(r"\batomic_bool\s+__dredd_already_recorded_(\d+)\s*\[\s*(\d+)\s*\]")
ANCHOR_INCLUDE = '#include "gallivm/lp_bld_debug.h"'
FUNCTIONS = ("lvp_CreateGraphicsPipelines", "lvp_CreateComputePipelines")


def find_arrays(mutated_dir):
    arrays = {}
    for path in sorted(mutated_dir.rglob("*")):
        if path.suffix not in (".c", ".cc", ".cpp") or not path.is_file():
            continue
        text = path.read_text(errors="replace")
        if "DREDD PRELUDE START" not in text:
            continue
        for idx, size in DEF_RE.findall(text):
            idx, size = int(idx), int(size)
            if idx in arrays and arrays[idx][0] != size:
                sys.exit(f"error: __dredd_already_recorded_{idx} defined with sizes "
                         f"{arrays[idx][0]} ({arrays[idx][1]}) and {size} ({path})")
            arrays.setdefault(idx, (size, path))
    if not arrays:
        sys.exit(f"error: no __dredd_already_recorded_* definitions found under {mutated_dir}; "
                 "was Dredd run with --allow-reset-of-tracking-counters?")
    expected = set(range(len(arrays)))
    if set(arrays) != expected:
        missing = sorted(expected - set(arrays))[:10]
        sys.exit(f"error: array indices are not 0..{len(arrays) - 1}; missing e.g. {missing}")
    return {i: arrays[i][0] for i in sorted(arrays)}


def insert_call(text, func):
    m = re.search(rf"\b{func}\s*\(", text)
    if not m:
        sys.exit(f"error: {func} not found in lvp_pipeline.c")
    brace = text.find("{", m.end())
    if brace == -1:
        sys.exit(f"error: no body found for {func}")
    return text[:brace + 1] + "\n   __dredd_reset_tracking();" + text[brace + 1:]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("mesa_dir", type=Path)
    ap.add_argument("--mutated-dir", default="src/compiler/nir")
    args = ap.parse_args()

    target = args.mesa_dir / "src/gallium/frontends/lavapipe/lvp_pipeline.c"
    text = target.read_text()
    if MARKER in text:
        sys.exit(f"error: {target} already has the reset code; start from clean sources")
    if ANCHOR_INCLUDE not in text:
        sys.exit(f"error: anchor line not found in {target}: {ANCHOR_INCLUDE}")

    arrays = find_arrays(args.mesa_dir / args.mutated_dir)

    block = [
        "",
        MARKER,
        "#include <stdatomic.h>",
        "#include <string.h>",
        "",
        *[f"extern atomic_bool __dredd_already_recorded_{i}[{n}];" for i, n in arrays.items()],
        "",
        "static void __dredd_reset_tracking(void) {",
        *[f"  memset(__dredd_already_recorded_{i}, 0, sizeof(__dredd_already_recorded_{i}));"
          for i in arrays],
        "}",
        "",
    ]
    text = text.replace(ANCHOR_INCLUDE, ANCHOR_INCLUDE + "\n" + "\n".join(block), 1)
    for func in FUNCTIONS:
        text = insert_call(text, func)
    target.write_text(text)

    print(f"Added reset for {len(arrays)} tracking arrays "
          f"({sum(arrays.values()):,} mutants) to {target}")
    print(f"Reset called at the start of: {', '.join(FUNCTIONS)}")


if __name__ == "__main__":
    main()