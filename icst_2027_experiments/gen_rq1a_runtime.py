#!/usr/bin/env python3
"""RQ1(a): runtime of isolated reachability runs, as LaTeX macros.

Reads the CSV written by aws/check_isolated_runtime.sh --csv. Only complete runs
(every test has a run_info.json, i.e. the largest test count in the file) are
used; aborted or partly compressed runs are listed on the console and skipped.

Usage:
  python3 icst_2027_experiments/gen_rq1a_runtime.py \
      results/reachability/runtimes/isolated_runtimes.csv \
      --out icst_2027_experiments/generated/rq1a_runtime_macros.tex

Macros: \\IsoHoursMin, \\IsoHoursMax (rounded to whole hours), \\IsoRuntimeRuns (how many
complete runs the range is from, as a word).
"""
import argparse
import csv

WORDS = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten"]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("csv")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    with open(args.csv) as f:
        rows = list(csv.DictReader(line for line in f if not line.startswith("#")))
    if not rows:
        raise SystemExit(f"no runs in {args.csv}")
    full = max(int(r["tests"]) for r in rows)
    complete = [r for r in rows if int(r["tests"]) == full]
    for r in rows:
        tag = "used" if r in complete else f"skipped ({int(r['tests']):,} of {full:,} tests)"
        print(f"  {r['host']} {r['run']}: {float(r['hours']):.1f} h  {tag}")

    hours = [float(r["hours"]) for r in complete]
    lo, hi = round(min(hours)), round(max(hours))
    n = len(complete)
    print(f"isolated runtime: {lo}--{hi} h over {n} complete runs of {full:,} tests")

    macros = ["% Generated by gen_rq1a_runtime.py -- do not edit by hand.",
              f"% source: {args.csv}",
              f"\\newcommand{{\\IsoHoursMin}}{{{lo}}}",
              f"\\newcommand{{\\IsoHoursMax}}{{{hi}}}",
              f"\\newcommand{{\\IsoRuntimeRuns}}{{{WORDS[n] if n < len(WORDS) else n}}}"]
    with open(args.out, "w") as f:
        f.write("\n".join(macros) + "\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()