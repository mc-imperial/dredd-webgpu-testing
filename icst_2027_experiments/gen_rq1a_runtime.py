#!/usr/bin/env python3
"""RQ1(a): runtime of the reachability runs, as LaTeX macros.

Isolated: reads the CSV written by analysis/check_isolated_runtime.sh --csv
(reconstructed from file timestamps on the instances). Only complete runs (the
largest test count in the file) are used; aborted or partly compressed runs are
listed on the console and skipped.

Shared: reads the raw runs directly (<shared-raw>/run-*/<configuration>/servers-*/
repeat-*). Each runner invocation's run_info.json records its time_seconds. A
subtree-no-cache repeat is one invocation; a file-subtrees-no-cache repeat is one
invocation per test file, run one after another, so its runtime is the sum.

Usage:
  python3 icst_2027_experiments/gen_rq1a_runtime.py \
      --isolated results/reachability/runtimes/isolated_runtimes.csv \
      --shared-raw results/reachability/raw/shared-v2 \
      --out icst_2027_experiments/generated/rq1a_runtime_macros.tex

Macros:
  \\IsoHoursMin, \\IsoHoursMax          whole hours
  \\IsoRuntimeRuns                      complete isolated runs measured (word)
  \\ShSubHoursMin, \\ShSubHoursMax      one decimal place
  \\ShFileHoursMin, \\ShFileHoursMax    one decimal place
  \\ShSubRuntimeRuns, \\ShFileRuntimeRuns
"""
import argparse
import csv
import glob
import json
import os

WORDS = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten"]
SHARED = [("subtree-no-cache", "Sub"), ("file-subtrees-no-cache", "File")]


def word(n):
    return WORDS[n] if n < len(WORDS) else str(n)


def read(path):
    with open(path) as f:
        return list(csv.DictReader(line for line in f if not line.startswith("#")))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--isolated", required=True)
    ap.add_argument("--shared-raw", required=True, help="folder holding the raw shared runs (run-*/...)")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    macros = ["% Generated by gen_rq1a_runtime.py -- do not edit by hand.",
              f"% sources: {args.isolated}, {args.shared_raw}"]

    rows = read(args.isolated)
    if not rows:
        raise SystemExit(f"no runs in {args.isolated}")
    full = max(int(r["tests"]) for r in rows)
    complete = [r for r in rows if int(r["tests"]) == full]
    print("isolated:")
    for r in rows:
        tag = "used" if r in complete else f"skipped ({int(r['tests']):,} of {full:,} tests)"
        print(f"  {r['host']} {r['run']}: {float(r['hours']):.1f} h  {tag}")
    hours = [float(r["hours"]) for r in complete]
    lo, hi = round(min(hours)), round(max(hours))
    print(f"  -> {lo}--{hi} h over {len(complete)} complete runs of {full:,} tests")
    macros += [f"\\newcommand{{\\IsoHoursMin}}{{{lo}}}",
               f"\\newcommand{{\\IsoHoursMax}}{{{hi}}}",
               f"\\newcommand{{\\IsoRuntimeRuns}}{{{word(len(complete))}}}"]

    for cfg, tag in SHARED:
        dirs = sorted(glob.glob(os.path.join(args.shared_raw, "run-*", cfg, "servers-*", "repeat-*")))
        print(f"{cfg}:")
        if not dirs:
            raise SystemExit(f"  no {cfg} runs under {args.shared_raw}")
        hours = []
        for d in dirs:
            top = os.path.join(d, "run_info.json")
            infos = [top] if os.path.exists(top) else sorted(glob.glob(os.path.join(d, "*", "run_info.json")))
            if not infos:
                raise SystemExit(f"  {d}: no run_info.json")
            loaded = [json.load(open(p)) for p in infos]
            h = sum(i["time_seconds"] for i in loaded) / 3600
            nonzero = sum(i.get("returncode", 0) != 0 for i in loaded)
            timed_out = sum(bool(i.get("timed_out")) for i in loaded)
            print(f"  {os.path.relpath(d, args.shared_raw)}: {h:.2f} h, {len(loaded)} invocation(s), "
                  f"{nonzero} non-zero exit, {timed_out} timed out")
            hours.append(h)
        print(f"  -> {min(hours):.1f}--{max(hours):.1f} h over {len(hours)} runs")
        macros += [f"\\newcommand{{\\Sh{tag}HoursMin}}{{{min(hours):.1f}}}",
                   f"\\newcommand{{\\Sh{tag}HoursMax}}{{{max(hours):.1f}}}",
                   f"\\newcommand{{\\Sh{tag}RuntimeRuns}}{{{word(len(hours))}}}"]

    with open(args.out, "w") as f:
        f.write("\n".join(macros) + "\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()