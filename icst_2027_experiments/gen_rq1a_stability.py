#!/usr/bin/env python3
"""Generate the RQ1(a) stability-across-repeats outputs for the paper.

Reads the merged summary that merge_mappings.py writes, plus the per-run
*_counts_summary.txt files that plot_reachability.py writes, and produces,
in --out-dir:

  rq1a_stability_macros.tex   \\newcommand macros for numbers used in prose
  rq1a_stability_table.tex    a tabular of stability measures

Uses parse() from gen_rq1a_reachability.py, which must sit in the same folder.
"""
import argparse
import re
import sys
from pathlib import Path

from gen_rq1a_reachability import fmt_int, fmt_int_range, parse as parse_run_summary


def num(s):
    return int(s.replace(",", ""))


def need(pattern, text, path):
    m = re.search(pattern, text, re.M)
    if not m:
        sys.exit(f"{path}: could not find pattern {pattern!r}")
    return m


def parse_merged(path):
    text = path.read_text()
    d = {}
    m = need(r"Merged (\d+) runs with --max-tests (\d+)", text, path)
    d["runs"], d["max_tests"] = int(m.group(1)), int(m.group(2))
    d["reached_any"] = num(need(r"Mutants reached in at least one run:\s+([\d,]+)", text, path).group(1))
    d["dropped_some_run"] = num(need(r"dropped: > \d+ tests in some run:\s+([\d,]+)", text, path).group(1))
    d["dropped_union"] = num(need(r"dropped: union grew past \d+:\s+([\d,]+)", text, path).group(1))
    d["kept"] = num(need(r"kept \(union <= \d+ tests\):\s+([\d,]+)", text, path).group(1))
    m = need(r"Of the ([\d,]+) candidates, ([\d,]+) \(([\d.]+)%\) have a union", text, path)
    d["candidates"], d["union_grew"], d["union_grew_pct"] = num(m.group(1)), num(m.group(2)), float(m.group(3))
    d["some_runs_only"] = num(need(r"Reached in only some runs:\s+([\d,]+)", text, path).group(1))

    # Internal consistency checks, so a format change can't silently give wrong numbers.
    if d["reached_any"] - d["dropped_some_run"] != d["candidates"]:
        sys.exit(f"{path}: reached - dropped(some run) != candidates")
    if d["candidates"] - d["dropped_union"] != d["kept"]:
        sys.exit(f"{path}: candidates - dropped(union) != kept")
    # A union can only exceed the limit if it is larger than every single run,
    # so the dropped-by-union mutants are a subset of the union-grew ones.
    if d["dropped_union"] > d["union_grew"]:
        sys.exit(f"{path}: more mutants dropped by union than had a union larger than any run")
    return d


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--merged-summary", type=Path, required=True, help="merge_mappings.py *_summary.txt")
    ap.add_argument("run_summaries", nargs="+", type=Path, help="per-run *_counts_summary.txt files")
    ap.add_argument("--out-dir", type=Path, required=True)
    args = ap.parse_args()

    merged = parse_merged(args.merged_summary)
    runs = [parse_run_summary(p) for p in sorted(args.run_summaries)]
    if len(runs) != merged["runs"]:
        sys.exit(f"{len(runs)} run summaries given, but the merge used {merged['runs']} runs")
    n = merged["max_tests"]
    if not all(n in r["thresholds"] for r in runs):
        sys.exit(f"run summaries have no 'at most {n} tests' row")

    reached = [r["reached"] for r in runs]
    at_most = [r["thresholds"][n][0] for r in runs]
    same_pct = 100.0 - merged["union_grew_pct"]

    args.out_dir.mkdir(parents=True, exist_ok=True)
    macros = [
        "% Generated by gen_rq1a_stability.py -- do not edit by hand.",
        f"% Source: {args.merged_summary}",
        f"\\newcommand{{\\StabRuns}}{{{merged['runs']}}}",
        f"\\newcommand{{\\StabMaxTests}}{{{n}}}",
        f"\\newcommand{{\\StabReachedPerRun}}{{{fmt_int_range(reached)}}}",
        f"\\newcommand{{\\StabReachedAny}}{{{fmt_int(merged['reached_any'])}}}",
        f"\\newcommand{{\\StabReachedSomeRunsOnly}}{{{fmt_int(merged['some_runs_only'])}}}",
        f"\\newcommand{{\\StabAtMostPerRun}}{{{fmt_int_range(at_most)}}}",
        f"\\newcommand{{\\StabCandidates}}{{{fmt_int(merged['candidates'])}}}",
        f"\\newcommand{{\\StabUnionGrew}}{{{fmt_int(merged['union_grew'])}}}",
        f"\\newcommand{{\\StabUnionGrewPct}}{{{merged['union_grew_pct']:.1f}\\%}}",
        f"\\newcommand{{\\StabUnionSamePct}}{{{same_pct:.1f}\\%}}",
        f"\\newcommand{{\\StabDroppedUnion}}{{{fmt_int(merged['dropped_union'])}}}",
        f"\\newcommand{{\\StabUnionGrewKept}}{{{fmt_int(merged['union_grew'] - merged['dropped_union'])}}}",
        f"\\newcommand{{\\StabKept}}{{{fmt_int(merged['kept'])}}}",
    ]
    (args.out_dir / "rq1a_stability_macros.tex").write_text("\n".join(macros) + "\n")

    rows = [
        ("Repeats", str(merged["runs"])),
        ("Mutants reached, per repeat", fmt_int_range(reached)),
        ("Mutants reached in at least one repeat", fmt_int(merged["reached_any"])),
        ("\\quad of which reached in only some repeats", fmt_int(merged["some_runs_only"])),
        (f"Mutants reached by $\\leq${n} tests, per repeat", fmt_int_range(at_most)),
        (f"Mutants never reached by $>${n} tests in any repeat", fmt_int(merged["candidates"])),
        ("\\quad of which reached from different tests across repeats",
         f"{fmt_int(merged['union_grew'])} ({merged['union_grew_pct']:.1f}\\%)"),
        (f"\\qquad of which union exceeds {n} tests (dropped)", fmt_int(merged["dropped_union"])),
        ("Mutants in the merged mapping", fmt_int(merged["kept"])),
    ]
    table = [
        "% Generated by gen_rq1a_stability.py -- do not edit by hand.",
        "\\begin{tabular}{lr}",
        "\\toprule",
        "Measure & Value \\\\",
        "\\midrule",
        *[f"{a} & {b} \\\\" for a, b in rows],
        "\\bottomrule",
        "\\end{tabular}",
    ]
    (args.out_dir / "rq1a_stability_table.tex").write_text("\n".join(table) + "\n")
    print(f"Wrote stability macros and table to {args.out_dir}")


if __name__ == "__main__":
    main()
    