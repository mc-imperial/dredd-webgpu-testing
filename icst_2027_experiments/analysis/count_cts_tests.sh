#!/usr/bin/env bash
# Count the WebGPU CTS test cases, using the CTS in the experiment image (/data/cts, the
# copy the runs used), and write LaTeX macros.
#
# Lists every case with the CTS's own runner (tools/run_node --list), offline, and saves
# the listings so the counts can be checked:
#   results/cts-listing/webgpu.txt         all webgpu:* cases
#   results/cts-listing/shader.txt         the webgpu:shader,* cases
#   results/cts-listing/by_area.csv        cases per second-level area (e.g. shader,execution)
#   results/cts-listing/image.txt          the image and CTS commit listed
# Macros (generated/setup_cts_counts.tex):
#   \CtsCommit, \CtsCommitDate             the CTS commit in the image
#   \CtsTestsTotal                         webgpu:* cases
#   \CtsShaderTests, \CtsShaderTestsPct    webgpu:shader,* cases, and their share of all
# Also compares the shader listing with the tests the reachability runs saw
# (results/reachability/matrix/tests.txt, if present) and warns if they differ.
#
# Usage (from the repository root):
#   bash icst_2027_experiments/count_cts_tests.sh
# Environment: IMAGE (default dredd-webgpu-testing:reachability-stability),
#              OUT_DIR (default results/cts-listing), GEN (default icst_2027_experiments/generated)
set -euo pipefail

IMAGE="${IMAGE:-dredd-webgpu-testing:reachability-stability}"
OUT_DIR="${OUT_DIR:-results/cts-listing}"
GEN="${GEN:-icst_2027_experiments/generated}"
TESTS_TXT="${TESTS_TXT:-results/reachability/matrix/tests.txt}"
mkdir -p "$OUT_DIR" "$GEN"

list() {   # $1: query
    docker run --rm --network none "$IMAGE" bash -c \
        "cd /data/cts && ./tools/run_node --list '$1'" | grep '^webgpu:' | sort -u
}

echo "listing webgpu:* in $IMAGE ..."
list 'webgpu:*' > "$OUT_DIR/webgpu.txt"
echo "listing webgpu:shader,* ..."
list 'webgpu:shader,*' > "$OUT_DIR/shader.txt"
commit=$(docker run --rm --network none "$IMAGE" git -C /data/cts log -1 --format='%h %cs')
{ echo "image: $(docker image inspect -f '{{.Id}} (built {{.Created}})' "$IMAGE")"
  echo "cts: /data/cts $commit"; } | tee "$OUT_DIR/image.txt"

python3 - "$OUT_DIR" "$GEN/setup_cts_counts.tex" "$TESTS_TXT" "$commit" <<'EOF'
import collections, os, sys
out_dir, tex, tests_txt, commit = sys.argv[1:5]
read = lambda p: [l.strip() for l in open(p) if l.strip()]
allc, shader = read(f"{out_dir}/webgpu.txt"), read(f"{out_dir}/shader.txt")
if not allc or not shader:
    sys.exit("empty listing: check the run_node output")
in_all = [c for c in allc if c.startswith("webgpu:shader,")]
if set(in_all) != set(shader):
    print(f"WARNING: webgpu:* has {len(in_all):,} shader cases, webgpu:shader,* has {len(shader):,}")

# cases per area: webgpu:<a>,<b>,... -> "a,b"
area = collections.Counter(",".join(c.split(":")[1].split(",")[:2]) for c in allc)
with open(f"{out_dir}/by_area.csv", "w") as f:
    f.write("area,cases\n")
    for a, n in sorted(area.items()):
        f.write(f"{a},{n}\n")

fmt = lambda n: f"{n:,}".replace(",", "{,}")
h, date = commit.split()
lines = ["% Generated by count_cts_tests.sh -- do not edit by hand.",
         f"\\newcommand{{\\CtsCommit}}{{{h}}}",
         f"\\newcommand{{\\CtsCommitDate}}{{{date}}}",
         f"\\newcommand{{\\CtsTestsTotal}}{{{fmt(len(allc))}}}",
         f"\\newcommand{{\\CtsShaderTests}}{{{fmt(len(shader))}}}",
         f"\\newcommand{{\\CtsShaderTestsPct}}{{{100 * len(shader) / len(allc):.0f}\\%}}"]
open(tex, "w").write("\n".join(lines) + "\n")
print(f"webgpu:* {len(allc):,} cases; webgpu:shader,* {len(shader):,} "
      f"({100 * len(shader) / len(allc):.1f}%); wrote {tex}")
for a, n in sorted(area.items(), key=lambda x: -x[1]):
    print(f"  {a:40} {n:>8,}")

if os.path.exists(tests_txt):
    seen = set(read(tests_txt))
    s = set(shader)
    print(f"reachability tests.txt: {len(seen):,} tests; in the listing: {len(seen & s):,}; "
          f"listed but not in tests.txt: {len(s - seen):,}; in tests.txt but not listed: {len(seen - s):,}")
    for name, xs in (("listed, not in tests.txt", s - seen), ("in tests.txt, not listed", seen - s)):
        for x in sorted(xs)[:5]:
            print(f"  e.g. {name}: {x}")
else:
    print(f"note: {tests_txt} not found, so no comparison with the reachability runs")
EOF